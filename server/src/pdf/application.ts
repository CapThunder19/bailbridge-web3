import type { OffenceVariant } from "../screening/offences.js";
import { offenceLabel } from "../screening/offences.js";
import { REASON_TEXT, type CustodyPeriod, type ScreeningResult } from "../screening/engine.js";
import { inclusiveDays } from "../screening/dates.js";
import { Flow } from "./layout.js";

export interface ApplicationPdfInput {
  caseId: string;
  personName: string;
  age: number | null;
  caseRef: string;
  court: string;
  stage: string;
  offence: OffenceVariant;
  custodyPeriods: CustodyPeriod[];
  excludedNote: string;
  previousConviction: "yes" | "no" | "unknown";
  otherPendingCases: "yes" | "no" | "unknown";
  screening: ScreeningResult;
  lawyerName: string;
  generatedAt: Date;
}

const fractionWords = { "1/2": "one-half", "1/3": "one-third" } as const;

/**
 * DRAFT bail application under s.479 BNSS. Clearly marked as a draft for
 * lawyer review. Contains no hash of itself.
 */
export async function buildApplicationPdf(a: ApplicationPdfInput): Promise<Uint8Array> {
  const s = a.screening;
  if (s.fraction === null || s.thresholdDays === null || s.qualifyingDays === null) {
    throw new Error("Screening has no computed threshold; a draft application cannot be generated.");
  }
  const f = await Flow.create("DRAFT");
  f.doc.setTitle(`DRAFT s.479 BNSS bail application — ${a.caseRef}`);
  f.doc.setSubject("Draft generated by BailBridge (prototype). Synthetic demo data.");
  f.doc.setProducer("BailBridge prototype");
  f.doc.setCreator("BailBridge prototype");
  f.doc.setCreationDate(a.generatedAt);
  f.doc.setModificationDate(a.generatedAt);

  f.text("DRAFT — FOR LAWYER REVIEW — NOT AN ORDER, NOT FILED WITH ANY COURT", { bold: true, color: "red", size: 10 });
  f.text("Prototype output on synthetic demo data. Every figure below must be independently verified.", {
    color: "grey",
    size: 9,
    gap: 10,
  });

  f.text(`IN THE COURT OF ${a.court.toUpperCase()}`, { bold: true, size: 12 });
  f.text(`Case reference: ${a.caseRef}`, { gap: 10 });
  f.text("APPLICATION FOR RELEASE ON BAIL UNDER SECTION 479 OF THE BHARATIYA NAGARIK SURAKSHA SANHITA, 2023", {
    bold: true,
    size: 12,
    gap: 10,
  });

  f.heading("1. Applicant");
  f.rows([
    ["Name", a.personName],
    ["Age", a.age === null ? "Not recorded" : String(a.age)],
    ["Stage of proceedings", a.stage],
    ["Offence (as recorded)", offenceLabel(a.offence)],
    ["Former IPC equivalent", a.offence.mappedAct ? `${a.offence.mappedAct} s.${a.offence.mappedSection}` : "—"],
    ["Maximum punishment", a.offence.punishmentText],
  ]);

  f.heading("2. Period of detention");
  f.rows(
    a.custodyPeriods.map((p, i) => [
      `Custody period ${i + 1}`,
      `${p.start} to ${p.end ?? `${s.asOf} (continuing)`} — ${inclusiveDays(p.start, p.end ?? s.asOf)} days`,
    ]),
  );
  f.rows([
    ["Counted custody", `${s.countedDays} days (inclusive of first and last day)`],
    [
      "Excluded days",
      `${s.excludedDays} days attributable to delay caused by the accused${a.excludedNote ? ` (${a.excludedNote})` : ""}`,
    ],
    ["Qualifying detention", `${s.qualifyingDays} days as of ${s.asOf}`],
    ["Maximum term (days)", `${s.maxSentenceDays} days (prototype convention: years x 365, months x 30)`],
    ["Applicable fraction", `${fractionWords[s.fraction]} (${s.fraction})`],
    ["Threshold", `${s.thresholdDays} days (rounded up)`],
    ["Estimated threshold date", s.estimatedThresholdDate ?? "Not projected"],
  ]);

  f.heading("3. Grounds");
  const grounds = [
    `The applicant has been detained as an undertrial for ${s.qualifyingDays} qualifying days, which on the calculation above equals or exceeds ${fractionWords[s.fraction]} of the maximum period of imprisonment specified for the offence (${s.thresholdDays} days).`,
    a.previousConviction === "no"
      ? "On instructions, the applicant has never been convicted of any offence; the proviso to s.479(1) (one-third) is therefore relied upon, subject to verification."
      : a.previousConviction === "yes"
        ? "The applicant has a recorded previous conviction; the one-half threshold under s.479(1) has been applied."
        : "The applicant's conviction history has not been verified; the one-half threshold under s.479(1) has been applied conservatively.",
    "The offence is not one punishable with death or imprisonment for life.",
    a.otherPendingCases === "no"
      ? "On instructions, no investigation, inquiry or trial is pending against the applicant in any other offence or case (s.479(2)). This must be verified before filing."
      : "The position under s.479(2) (other pending offences or cases) requires verification before filing.",
    "Under s.479(3) BNSS the Superintendent of the jail is required, on completion of the relevant period, to forthwith make a written application to the Court for release.",
  ];
  grounds.forEach((g, i) => f.text(`(${String.fromCharCode(97 + i)}) ${g}`, { indent: 10 }));

  f.heading("4. Prayer");
  f.text(
    "It is therefore respectfully prayed that this Hon'ble Court may be pleased to consider the release of the applicant on bail, with or without sureties, or on bond, under Section 479 of the Bharatiya Nagarik Suraksha Sanhita, 2023, on such conditions as this Hon'ble Court deems fit.",
    { gap: 10 },
  );
  f.text(`Counsel for the applicant: ${a.lawyerName}`, { bold: true, gap: 12 });

  f.rule();
  f.heading("Screening notes and caveats (remove before filing)");
  for (const code of s.reasonCodes) f.text(`• ${REASON_TEXT[code]}`, { size: 9, indent: 6, color: "grey" });
  for (const m of s.missingInfo) f.text(`• Missing: ${m}`, { size: 9, indent: 6, color: "grey" });
  for (const c of [
    "This is a screening aid. It does not decide bail and is not legal advice.",
    "The release decision rests with the Court; the calculation must be checked against the record.",
    "Day counts use prototype conventions that require legal validation.",
    `Rule version ${s.ruleVersion}. Legal source: ${s.legalSource}`,
    `Offence data source: ${a.offence.sourceUrl}`,
  ]) {
    f.text(`• ${c}`, { size: 9, indent: 6, color: "grey" });
  }

  f.footer(`BailBridge DRAFT — case ${a.caseId.slice(0, 10)}… — generated ${a.generatedAt.toISOString()} — synthetic demo data`);
  return f.doc.save();
}
